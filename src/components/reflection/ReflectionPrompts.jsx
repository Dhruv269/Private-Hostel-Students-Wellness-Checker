import React, { useState } from 'react';
import { 
  PenTool, 
  Check, 
  Copy,
  Info,
  Sparkles,
  Lock,
  ArrowRight
} from 'lucide-react';
import { STATIC_REFLECTION_PROMPTS } from '../../data/mockData';

export default function ReflectionPrompts() {
  const [copiedId, setCopiedId] = useState(null);
  const [selectedPrompt, setSelectedPrompt] = useState(STATIC_REFLECTION_PROMPTS[0]);
  const [scratchpadText, setScratchpadText] = useState('');
  const [activeCategory, setActiveCategory] = useState('All');

  const categories = ['All', ...new Set(STATIC_REFLECTION_PROMPTS.map((p) => p.category))];

  const filteredPrompts = activeCategory === 'All'
    ? STATIC_REFLECTION_PROMPTS
    : STATIC_REFLECTION_PROMPTS.filter((p) => p.category === activeCategory);

  const handleCopyPrompt = (item) => {
    navigator.clipboard.writeText(item.prompt);
    setCopiedId(item.id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  return (
    <div className="reflections-page-cinematic">
      <header className="page-cinematic-header">
        <div className="header-eyebrow">
          <Sparkles size={14} className="text-emerald-400" aria-hidden="true" />
          <span>Mindful Exercises</span>
        </div>
        <h1 className="header-main-title">
          Supportive Reflection Prompts
        </h1>
        <p className="header-lead">
          Curated, non-judgmental prompts to help you unpack hostel life, academic pressures, and personal boundaries.
        </p>
      </header>

      {/* Non-AI & Non-Diagnostic Disclosure Banner */}
      <div className="cinematic-card reflections-disclosure-banner" role="note">
        <Info size={18} className="text-emerald-400 flex-shrink-0" aria-hidden="true" />
        <p className="disclosure-text">
          <strong>Curated Human Prompts:</strong> These exercises are structured self-reflection questions. They are <strong>not</strong> generated by an AI model and do not constitute clinical psychological assessments.
        </p>
      </div>

      {/* Category Pills */}
      <div className="reflections-category-pills" role="tablist" aria-label="Prompt categories">
        {categories.map((cat) => (
          <button
            key={cat}
            type="button"
            role="tab"
            aria-selected={activeCategory === cat}
            className={`category-pill-btn ${activeCategory === cat ? 'is-active' : ''}`}
            onClick={() => setActiveCategory(cat)}
          >
            {cat}
          </button>
        ))}
      </div>

      <div className="reflections-two-col-layout">
        {/* Prompts List Column */}
        <div className="prompts-scroll-column">
          {filteredPrompts.map((item) => {
            const isSelected = selectedPrompt?.id === item.id;
            return (
              <div 
                key={item.id} 
                role="button"
                tabIndex={0}
                aria-pressed={isSelected}
                aria-label={`Select reflection prompt: ${item.category}`}
                className={`cinematic-card prompt-tile-card ${isSelected ? 'is-selected' : ''}`}
                onClick={() => setSelectedPrompt(item)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    setSelectedPrompt(item);
                  }
                }}
              >
                <div className="prompt-tile-header">
                  <span className="prompt-category-tag">{item.category}</span>
                  <button
                    type="button"
                    className="btn-cinematic-icon-text"
                    onClick={(e) => {
                      e.stopPropagation();
                      handleCopyPrompt(item);
                    }}
                    title="Copy prompt text to clipboard"
                    aria-label={`Copy prompt: ${item.category}`}
                  >
                    {copiedId === item.id ? (
                      <>
                        <Check size={13} className="text-emerald-400" aria-hidden="true" />
                        <span>Copied</span>
                      </>
                    ) : (
                      <>
                        <Copy size={13} aria-hidden="true" />
                        <span>Copy</span>
                      </>
                    )}
                  </button>
                </div>

                <blockquote className="prompt-tile-quote">
                  "{item.prompt}"
                </blockquote>

                <div className="prompt-tile-footer">
                  <span className="prompt-tag-badge">Topic: {item.tag}</span>
                  {isSelected && (
                    <span className="prompt-active-indicator">
                      <span>Active in Scratchpad</span>
                      <ArrowRight size={12} aria-hidden="true" />
                    </span>
                  )}
                </div>
              </div>
            );
          })}
        </div>

        {/* Private Scratchpad Column (Sticky) */}
        <div className="scratchpad-sticky-column">
          <div className="cinematic-card scratchpad-dark-card">
            <div className="scratchpad-header">
              <div className="scratchpad-title-group">
                <PenTool size={16} className="text-emerald-400" aria-hidden="true" />
                <h2 className="scratchpad-title">Private Journal Scratchpad</h2>
              </div>
              <span className="badge-demo-tag">In-Memory Only</span>
            </div>

            <div className="scratchpad-active-callout">
              <span className="callout-cat">{selectedPrompt.category}</span>
              <p className="callout-quote">"{selectedPrompt.prompt}"</p>
            </div>

            <label htmlFor="scratchpad-input" className="sr-only">Personal reflection scratchpad</label>
            <textarea
              id="scratchpad-input"
              className="cinematic-textarea scratchpad-textarea"
              value={scratchpadText}
              onChange={(e) => setScratchpadText(e.target.value)}
              placeholder="Unload thoughts, frustrations, or intentions for tomorrow. Nothing written here is sent to a server or saved to a database..."
              rows={9}
            />

            <div className="scratchpad-action-bar">
              <span className="scratchpad-counter">
                {scratchpadText.length} characters
              </span>
              <button
                type="button"
                className="btn-cinematic-ghost btn-sm"
                onClick={() => setScratchpadText('')}
                disabled={!scratchpadText}
              >
                Clear Scratchpad
              </button>
            </div>

            <div className="scratchpad-security-note">
              <Lock size={13} className="text-emerald-400 flex-shrink-0" aria-hidden="true" />
              <span>
                <strong>Confidential:</strong> Even 3 minutes of journaling before sleeping helps quiet mental chatter in noisy hostels.
              </span>
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
