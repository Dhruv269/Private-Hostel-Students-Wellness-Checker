import React, { useState } from 'react';
import { 
  PenTool, 
  Check, 
  Copy,
  Info
} from 'lucide-react';
import { STATIC_REFLECTION_PROMPTS } from '../../data/mockData';

export default function ReflectionPrompts() {
  const [copiedId, setCopiedId] = useState(null);
  const [selectedPrompt, setSelectedPrompt] = useState(STATIC_REFLECTION_PROMPTS[0]);
  const [scratchpadText, setScratchpadText] = useState('');

  const handleCopyPrompt = (item) => {
    navigator.clipboard.writeText(item.prompt);
    setCopiedId(item.id);
    setTimeout(() => setCopiedId(null), 2000);
  };

  return (
    <div>
      <div style={{ marginBottom: '1.75rem' }}>
        <h1 style={{ fontSize: '1.75rem', marginBottom: '0.35rem' }}>
          Supportive Reflection Prompts
        </h1>
        <p style={{ color: 'var(--text-secondary)' }}>
          Pre-written, non-judgmental prompts to help you unpack hostel life, study pressure, and personal boundaries.
        </p>
      </div>

      {/* Non-AI & Non-Diagnostic Disclosure Banner */}
      <div style={{ 
        background: 'rgba(30, 41, 66, 0.45)', 
        border: '1px solid var(--border-subtle)', 
        borderRadius: 'var(--radius-md)', 
        padding: '0.85rem 1rem', 
        marginBottom: '1.75rem',
        display: 'flex',
        alignItems: 'flex-start',
        gap: '0.75rem'
      }}>
        <Info size={20} style={{ color: 'var(--color-primary-light)', flexShrink: 0, marginTop: '0.15rem' }} aria-hidden="true" />
        <div style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
          <strong style={{ color: 'var(--text-primary)' }}>Notice:</strong> These questions are curated, pre-written self-reflection exercises. They are <strong style={{ color: 'var(--text-primary)' }}>not</strong> generated by an AI model, and they are <strong style={{ color: 'var(--text-primary)' }}>not</strong> clinical psychological assessments. Use them as gentle journaling prompts.
        </div>
      </div>

      <div className="dashboard-split">
        {/* Prompts List */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '1rem' }}>
          {STATIC_REFLECTION_PROMPTS.map((item) => {
            const isSelected = selectedPrompt?.id === item.id;
            // Keyboard-accessible prompt card:
            // Using role="button", tabIndex={0}, and onKeyDown allows keyboard users
            // to navigate with Tab and select the card with Enter or Space.
            // (We use a container div with role="button" because nesting an HTML <button> 
            // inside another HTML <button> for the Copy button is invalid HTML).
            return (
              <div 
                key={item.id} 
                role="button"
                tabIndex={0}
                aria-pressed={isSelected}
                aria-label={`Select reflection prompt on ${item.category}`}
                className={`card ${isSelected ? 'card-elevated' : ''}`}
                style={{ 
                  cursor: 'pointer',
                  borderColor: isSelected ? 'var(--color-primary-light)' : 'var(--border-subtle)',
                  transition: 'all var(--transition-fast)',
                  textAlign: 'left'
                }}
                onClick={() => setSelectedPrompt(item)}
                onKeyDown={(e) => {
                  if (e.key === 'Enter' || e.key === ' ') {
                    e.preventDefault();
                    setSelectedPrompt(item);
                  }
                }}
              >
                <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.5rem' }}>
                  <span className="badge badge-calm" style={{ fontSize: '0.75rem' }}>
                    {item.category}
                  </span>
                  <button
                    type="button"
                    className="btn btn-ghost"
                    style={{ padding: '0.2rem 0.5rem', fontSize: '0.75rem' }}
                    onClick={(e) => {
                      e.stopPropagation();
                      handleCopyPrompt(item);
                    }}
                    title="Copy prompt text"
                    aria-label={`Copy prompt: ${item.category}`}
                  >
                    {copiedId === item.id ? (
                      <span style={{ display: 'flex', alignItems: 'center', gap: '0.25rem', color: 'var(--color-success)' }}>
                        <Check size={14} aria-hidden="true" /> Copied
                      </span>
                    ) : (
                      <span style={{ display: 'flex', alignItems: 'center', gap: '0.25rem', color: 'var(--text-muted)' }}>
                        <Copy size={14} aria-hidden="true" /> Copy
                      </span>
                    )}
                  </button>
                </div>

                <p style={{ fontSize: '0.95rem', color: 'var(--text-primary)', lineHeight: 1.6, margin: 0, fontWeight: 500 }}>
                  "{item.prompt}"
                </p>

                <div style={{ marginTop: '0.75rem', fontSize: '0.75rem', color: 'var(--color-primary-light)', fontWeight: 600 }}>
                  Tag: {item.tag} {isSelected ? '• Selected for Scratchpad' : ''}
                </div>
              </div>
            );
          })}
        </div>

        {/* Private Scratchpad for the selected prompt */}
        <div>
          <div className="card" style={{ position: 'sticky', top: '5rem' }}>
            <div className="card-header">
              <div className="card-title" style={{ fontSize: '1rem' }}>
                <PenTool size={18} style={{ color: 'var(--color-primary-light)' }} aria-hidden="true" />
                <span>Private Journal Scratchpad</span>
              </div>
              <span className="badge badge-demo">In-Memory</span>
            </div>

            <div style={{ 
              background: 'var(--bg-surface-elevated)', 
              borderRadius: 'var(--radius-md)', 
              padding: '0.75rem', 
              marginBottom: '1rem',
              borderLeft: '3px solid var(--color-accent-lavender)'
            }}>
              <div style={{ fontSize: '0.75rem', color: 'var(--text-muted)', marginBottom: '0.25rem' }}>
                Reflecting on: {selectedPrompt.category}
              </div>
              <div style={{ fontSize: '0.85rem', color: 'var(--text-primary)', fontStyle: 'italic' }}>
                "{selectedPrompt.prompt}"
              </div>
            </div>

            <label htmlFor="scratchpad-input" className="sr-only">Personal reflection scratchpad</label>
            <textarea
              id="scratchpad-input"
              className="textarea-field"
              value={scratchpadText}
              onChange={(e) => setScratchpadText(e.target.value)}
              placeholder="Jot down brief thoughts, frustrations, or plans for tonight. This scratchpad does not save anywhere—it is purely for processing your thoughts..."
              rows={8}
            />

            <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginTop: '0.75rem' }}>
              <span style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                {scratchpadText.length} characters
              </span>
              <button
                type="button"
                className="btn btn-ghost"
                onClick={() => setScratchpadText('')}
                disabled={!scratchpadText}
                style={{ fontSize: '0.75rem', padding: '0.25rem 0.5rem' }}
              >
                Clear Scratchpad
              </button>
            </div>

            <div style={{ 
              background: 'rgba(15, 23, 42, 0.5)', 
              borderRadius: 'var(--radius-sm)', 
              padding: '0.65rem', 
              marginTop: '1rem', 
              fontSize: '0.75rem', 
              color: 'var(--text-muted)',
              lineHeight: 1.4
            }}>
              🔒 <strong>Student Tip:</strong> Writing about your worries for even 3 minutes before going to bed is proven to quiet racing thoughts and improve sleep onset in noisy hostels.
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
